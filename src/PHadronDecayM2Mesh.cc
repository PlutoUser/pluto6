PHadronDecayM2Mesh::PHadronDecayM2Mesh(const Char_t *id, const  Char_t *de, Int_t key) :
    PHadronDecayM2(id, de, key) {
    if (is_channel < 0)
	Warning("PHadronDecayM2Mesh", "The model (%s) should be bound to CHANNELS only", de);

    //Generated by Gemini:
    double ml1 = PData::LMass(id1);
    double ml2 = PData::LMass(id2);
    ecm_grid_min = ml1 + ml2;
    ecm_grid_max = ecm_grid_min + 2.0; // 2 GeV window above threshold
    ecm_step = (ecm_grid_max - ecm_grid_min) / N_ECM;

    for (int k = 0; k < N_ECM; ++k) {
        is_calculated[k] = kFALSE;
    }
    //end generated by Gemini
};

