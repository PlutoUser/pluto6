void PHadronDecayM2Mesh::calculateSlice(int s, double ecm) {
    //Generated by Gemini:
    double m0[2] = {makeStaticData()->GetParticleMass(id1),
                    makeStaticData()->GetParticleMass(id2)};
    double ml[2] = {PData::LMass(id1), PData::LMass(id2)};
    double mh[2] = {ecm - ml[1], ecm - ml[0]};

    double dm1 = (mh[0] - ml[0]) / N1;
    double dm2 = (mh[1] - ml[1]) / N2;

    if (dm1 <= 0. || dm2 <= 0.) {
        is_calculated[s] = kTRUE;
        total_weight_sum[s] = 0.;
        valid_cells_cnt[s] = 0;
        return;
    }

    total_weight_sum[s] = 0.;
    valid_cells_cnt[s] = 0;
    const double safety_factor = 1.3;

    for (int i = 0; i < N1; ++i) {
        double m1_min = ml[0] + i * dm1;
        double m1_max = m1_min + dm1;

        for (int j = 0; j < N2; ++j) {
            double m2_min = ml[1] + j * dm2;
            double m2_max = m2_min + dm2;

            if (m1_min + m2_min >= ecm) {
                cell_ceiling[s][i][j] = 0.;
                continue;
            }

            double m1_pole = TMath::Min(TMath::Max(m0[0], m1_min), m1_max);
            double m2_pole = TMath::Min(TMath::Max(m0[1], m2_min), m2_max);

            double test_m1[6] = {m1_min, m1_max, m1_min, m1_max, (m1_min + m1_max) * 0.5, m1_pole};
            double test_m2[6] = {m2_min, m2_min, m2_max, m2_max, (m2_min + m2_max) * 0.5, m2_pole};

            double max_cell_y = 0.;
            for (int k = 0; k < 6; ++k) {
                if (test_m1[k] + test_m2[k] < ecm) {
                    double y_test = BWWeight(id1, ecm, test_m1[k], test_m2[k], didx1, id2, didx2);
                    if (y_test > max_cell_y) {
                        max_cell_y = y_test;
                    }
                }
            }

            double ceiling = max_cell_y * safety_factor;
            cell_ceiling[s][i][j] = ceiling;

            double weight = ceiling * dm1 * dm2;
            if (weight > 0.) {
                total_weight_sum[s] += weight;
                cell_cum_weight[s][valid_cells_cnt[s]] = total_weight_sum[s];
                cell_i[s][valid_cells_cnt[s]] = i;
                cell_j[s][valid_cells_cnt[s]] = j;
                valid_cells_cnt[s]++;
            }
        }
    }

    is_calculated[s] = kTRUE; // Flag as calculated
}

bool PHadronDecayM2Mesh::sampleM2(const double &ecm) {
    dynamic_mass1 = 0.;
    dynamic_mass2 = 0.;

    double ml[2] = {PData::LMass(id1), PData::LMass(id2)};
    if (ecm < ml[0] + ml[1]) {
        return kFALSE;
    }

    // Determine current ECM slice index
    int s = static_cast<int>((ecm - ecm_grid_min) / ecm_step);
    if (s < 0) s = 0;
    if (s >= N_ECM) s = N_ECM - 1;

    // Lazy initialization: compute grid only once per ECM slice
    if (!is_calculated[s]) {
        calculateSlice(s, ecm);
    }

    if (total_weight_sum[s] <= 0. || valid_cells_cnt[s] == 0) {
        return kFALSE;
    }

    double mh[2] = {ecm - ml[1], ecm - ml[0]};
    double dm1 = (mh[0] - ml[0]) / N1;
    double dm2 = (mh[1] - ml[1]) / N2;

    int counter = 0;
    const int max_attempts = 10000;

    // Fast sampling stage using precomputed lookup table
    while (counter < max_attempts) {
        counter++;

        // 1. Pick bin using CDF lookup
        double r_cell = PUtils::sampleFlat() * total_weight_sum[s];
        int chosen_idx = 0;
        while (chosen_idx < valid_cells_cnt[s] - 1 && r_cell > cell_cum_weight[s][chosen_idx]) {
            chosen_idx++;
        }

        int ci = cell_i[s][chosen_idx];
        int cj = cell_j[s][chosen_idx];

        double m1_min = ml[0] + ci * dm1;
        double m2_min = ml[1] + cj * dm2;

        // 2. Uniform sample within the bin
        double m1 = m1_min + PUtils::sampleFlat() * dm1;
        double m2 = m2_min + PUtils::sampleFlat() * dm2;

        if (m1 + m2 >= ecm) {
            continue;
        }

        double y = BWWeight(id1, ecm, m1, m2, didx1, id2, didx2);
        double ceiling = cell_ceiling[s][ci][cj];

        // Dynamic ceiling update (Self-healing)
        if (y > ceiling) {
            cell_ceiling[s][ci][cj] = y * 1.3;
            ceiling = y * 1.3;
        }

        if (PUtils::sampleFlat() * ceiling <= y) {
            dynamic_mass1 = m1;
            dynamic_mass2 = m2;
            return kTRUE;
        }
    }

    return kFALSE;
}

